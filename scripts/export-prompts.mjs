#!/usr/bin/env node
// Exports the prompt history of this project from the local Claude Code session
// transcripts into docs/prompts/, so the repository carries every prompt used.
//
// What is exported:
//   - every prompt typed by the user, including slash commands, in every session
//     whose working directory was this repository (or one of its worktrees)
//   - every brief the main session sent to a subagent (the Agent tool's prompt)
//   - prompts sent non-interactively (`claude -p`)
// What is not: model replies, tool output, skill bodies, system reminders,
// and anything from before the task arrived. Preparation sessions covered
// much that was unrelated to the task; what they produced is summarised in
// docs/process/00-preparation.md instead.
//
// The output, docs/prompts/README.md, is regenerated on every run; edit this
// script, not the output.
//
// Personal data is redacted (email addresses, the home directory, anything
// shaped like a key or token), but read the output before pushing it.
//
// Usage: pnpm prompts:export

import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

const TASK_RECEIVED = new Date("2026-11-27T09:30:00+01:00");

const repoRoot = resolve(import.meta.dirname, "..");
const outDir = join(repoRoot, "docs", "prompts");
const projectsDir = join(
  process.env.CLAUDE_CONFIG_DIR ?? join(homedir(), ".claude"),
  "projects",
);

// Claude Code names a project's transcript folder after its path, with every
// character other than a letter or a digit turned into "-".
const slug = (path) => path.replace(/[^A-Za-z0-9]/g, "-");
const slugs = [slug(repoRoot)];

const home = homedir();
const REDACTIONS = [
  [/[\w.+-]+@[\w-]+(\.[\w-]+)+/g, "[email]"],
  [new RegExp(home.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "g"), "~"],
  [
    /\b(sb_(secret|publishable)_[\w-]+|sk-[\w-]{20,}|gh[pousr]_\w{20,}|eyJ[\w-]{10,}\.[\w-]+\.[\w-]+)/g,
    "[redacted-key]",
  ],
];
const redact = (text) =>
  REDACTIONS.reduce(
    (out, [pattern, replacement]) => out.replace(pattern, replacement),
    text,
  );

// Text that reaches the transcript as a user message but was not typed by the user.
const NOT_TYPED = [
  "<local-command-stdout>",
  "<local-command-caveat>",
  "<task-notification>",
  "<side-sessions-event>",
  "<ci-monitor-event>",
  "Another Claude session sent a message",
  "This session is being continued from a previous conversation",
  "Base directory for this skill:",
  "Caveat: The messages below were generated by the user while running local commands",
];

function cleanPrompt(raw) {
  let text = raw.replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, "");
  // A shell command the user ran with "!": keep the command, drop its output.
  const shell = text.match(/<bash-input>([\s\S]*?)<\/bash-input>/);
  if (shell) return `! ${shell[1].trim()}`;
  const command = text.match(/<command-name>([\s\S]*?)<\/command-name>/);
  if (command) {
    const args =
      text.match(/<command-args>([\s\S]*?)<\/command-args>/)?.[1] ?? "";
    text = `${command[1].trim()} ${args.trim()}`;
  }
  text = text.trim();
  if (!text || NOT_TYPED.some((marker) => text.startsWith(marker))) return null;
  return text;
}

function textOf(content) {
  if (typeof content === "string") return content;
  if (!Array.isArray(content)) return "";
  return content
    .filter((block) => block?.type === "text" && typeof block.text === "string")
    .map((block) => block.text)
    .join("\n");
}

function readJsonl(file) {
  return readFileSync(file, "utf8")
    .split("\n")
    .filter(Boolean)
    .flatMap((line) => {
      try {
        return [JSON.parse(line)];
      } catch {
        return [];
      }
    });
}

function sessionTitle(folder, id, records) {
  const titleFile = join(folder, id, "custom-title.json");
  if (existsSync(titleFile)) {
    try {
      const title = JSON.parse(readFileSync(titleFile, "utf8")).customTitle;
      if (typeof title === "string" && title) return title;
    } catch {
      // fall through to the transcript's own title records
    }
  }
  const record = records.findLast(
    (r) => r.type === "custom-title" && typeof r.customTitle === "string",
  );
  return record?.customTitle ?? "Untitled session";
}

function collect() {
  const seen = new Set();
  const sessions = [];
  const folders = existsSync(projectsDir)
    ? readdirSync(projectsDir).filter((name) =>
        slugs.some((s) => name === s || name.startsWith(`${s}--`)),
      )
    : [];

  for (const folderName of folders) {
    const folder = join(projectsDir, folderName);
    for (const file of readdirSync(folder).filter((f) =>
      f.endsWith(".jsonl"),
    )) {
      const id = file.replace(/\.jsonl$/, "");
      const records = readJsonl(join(folder, file));
      const entries = [];

      for (const record of records) {
        if (!record.uuid || seen.has(record.uuid) || record.isSidechain)
          continue;

        if (
          record.type === "user" &&
          !record.isMeta &&
          !record.isCompactSummary &&
          !record.toolUseResult
        ) {
          const kind = record.origin?.kind;
          if (kind && kind !== "human") continue;
          const text = cleanPrompt(textOf(record.message?.content));
          if (!text) continue;
          seen.add(record.uuid);
          entries.push({
            at: record.timestamp,
            who:
              record.promptSource === "sdk" && !kind
                ? "non-interactive prompt (`claude -p`)"
                : "prompt",
            text:
              text === "[Request interrupted by user]"
                ? "_(interrupted the agent)_"
                : text,
          });
        }

        if (
          record.type === "assistant" &&
          Array.isArray(record.message?.content)
        ) {
          for (const block of record.message.content) {
            if (
              block?.type !== "tool_use" ||
              !["Agent", "Task"].includes(block.name)
            )
              continue;
            const prompt = block.input?.prompt;
            if (typeof prompt !== "string") continue;
            seen.add(record.uuid);
            const agent = block.input.subagent_type ?? "general-purpose";
            const description = block.input.description
              ? `: ${block.input.description}`
              : "";
            entries.push({
              at: record.timestamp,
              who: `brief to the \`${agent}\` agent${description}`,
              text: prompt,
              brief: true,
            });
          }
        }
      }

      if (entries.length > 0)
        sessions.push({
          id,
          title: sessionTitle(folder, id, records),
          entries,
        });
    }
  }
  return sessions;
}

const zone = Intl.DateTimeFormat().resolvedOptions().timeZone;
const format = new Intl.DateTimeFormat("sv-SE", {
  timeZone: zone,
  year: "numeric",
  month: "2-digit",
  day: "2-digit",
  hour: "2-digit",
  minute: "2-digit",
});
const when = (iso) => format.format(new Date(iso));

function fence(text) {
  const longest = Math.max(
    2,
    ...(text.match(/`+/g) ?? []).map((run) => run.length),
  );
  const ticks = "`".repeat(longest + 1);
  return `${ticks}text\n${text}\n${ticks}`;
}

function render(title, intro, sessions) {
  const lines = [
    `# ${title}`,
    "",
    intro,
    "",
    `Times are local (${zone}). Generated by \`pnpm prompts:export\`; do not edit by hand.`,
    "",
  ];
  const promptCount = sessions.reduce(
    (n, s) => n + s.entries.filter((e) => !e.brief).length,
    0,
  );
  const briefCount = sessions.reduce(
    (n, s) => n + s.entries.filter((e) => e.brief).length,
    0,
  );
  lines.push(
    `${sessions.length} sessions, ${promptCount} prompts, ${briefCount} subagent briefs.`,
    "",
  );

  lines.push("| Session | Started | Prompts |", "| --- | --- | --- |");
  for (const session of sessions) {
    lines.push(
      `| [${session.title}](#session-${session.id.slice(0, 8)}) | ${when(session.entries[0].at)} | ${session.entries.filter((e) => !e.brief).length} |`,
    );
  }
  lines.push("");

  for (const session of sessions) {
    lines.push(
      `<a id="session-${session.id.slice(0, 8)}"></a>`,
      "",
      `## ${session.title}`,
      "",
      `Session \`${session.id.slice(0, 8)}\`, ${when(session.entries[0].at)} to ${when(session.entries.at(-1).at)}.`,
      "",
    );
    for (const entry of session.entries) {
      const body = fence(redact(entry.text));
      if (entry.brief) {
        lines.push(
          `<details><summary>${when(entry.at)}, ${redact(entry.who)}</summary>`,
          "",
          body,
          "",
          "</details>",
          "",
        );
      } else {
        lines.push(`**${when(entry.at)}, ${entry.who}**`, "", body, "");
      }
    }
  }
  return `${lines.join("\n")}\n`;
}

function split(sessions, keep) {
  return sessions
    .map((session) => ({
      ...session,
      entries: session.entries.filter((entry) => keep(new Date(entry.at))),
    }))
    .filter((session) => session.entries.length > 0)
    .sort((a, b) => a.entries[0].at.localeCompare(b.entries[0].at));
}

const sessions = collect().map((session) => ({
  ...session,
  entries: session.entries.sort((a, b) => a.at.localeCompare(b.at)),
}));

mkdirSync(outDir, { recursive: true });
const taskSessions = split(sessions, (at) => at >= TASK_RECEIVED);
writeFileSync(
  join(outDir, "README.md"),
  render(
    "Prompt history",
    "Every prompt from the moment the task arrived (2026-11-27 09:30), in order, with every brief sent to a subagent. What was prepared before the task is summarised in [docs/process/00-preparation.md](../process/00-preparation.md).",
    taskSessions,
  ),
);
console.log(`→ docs/prompts/README.md: ${taskSessions.length} sessions`);
