#!/usr/bin/env node
// Mirrors the GitHub issues of this repository (the spec, its increments and
// their tickets) into docs/issues/, so the plan and its history are readable
// from the repository alone, without access to the issue tracker.
//
// One file per issue with its body and every comment, plus an index. The
// folder is regenerated on every run; edit the issues, not the output.
//
// Usage: pnpm issues:export   (needs the GitHub CLI, signed in)

import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const repoRoot = resolve(import.meta.dirname, "..");
const outDir = join(repoRoot, "docs", "issues");

function gh(args) {
  return execFileSync("gh", args, {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
}

const issues = JSON.parse(
  gh([
    "issue",
    "list",
    "--state",
    "all",
    "--limit",
    "1000",
    "--json",
    "number,title,state,labels,body,comments,createdAt,closedAt,url,author",
  ]),
).sort((a, b) => a.number - b.number);

const day = (iso) => (iso ? iso.slice(0, 16).replace("T", " ") + " UTC" : "");
const fileName = (issue) =>
  `${String(issue.number).padStart(3, "0")}-${issue.title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60)}.md`;

// Classify by title, following docs/agents/issue-tracker.md.
const kind = (issue) =>
  /^increment \d+/i.test(issue.title)
    ? "Increment"
    : /\bspec\b|^prd\b/i.test(issue.title)
      ? "Spec"
      : "Ticket";

mkdirSync(outDir, { recursive: true });
for (const file of readdirSync(outDir))
  if (/^\d{3}-.*\.md$/.test(file)) rmSync(join(outDir, file));

for (const issue of issues) {
  const labels =
    issue.labels.map((label) => `\`${label.name}\``).join(", ") || "none";
  const lines = [
    `# #${issue.number}: ${issue.title}`,
    "",
    `- **State:** ${issue.state.toLowerCase()}${issue.closedAt ? `, closed ${day(issue.closedAt)}` : ""}`,
    `- **Opened:** ${day(issue.createdAt)} by ${issue.author?.login ?? "unknown"}`,
    `- **Labels:** ${labels}`,
    `- **On GitHub:** ${issue.url}`,
    "",
    "## Body",
    "",
    issue.body?.trim() || "_No body._",
    "",
  ];
  if (issue.comments.length > 0) {
    lines.push("## Comments", "");
    for (const comment of issue.comments) {
      lines.push(
        `### ${comment.author?.login ?? "unknown"}, ${day(comment.createdAt)}`,
        "",
        comment.body.trim(),
        "",
      );
    }
  }
  writeFileSync(join(outDir, fileName(issue)), `${lines.join("\n")}\n`);
}

const index = [
  "# Issues",
  "",
  "A mirror of the GitHub issues: the spec, its increments and their tickets, with every comment. Generated by `pnpm issues:export`; do not edit by hand.",
  "",
];
if (issues.length === 0) {
  index.push("No issues yet. The spec is written in phase 1 (`/to-spec`).");
} else {
  index.push("| # | Kind | Title | State |", "| --- | --- | --- | --- |");
  for (const issue of issues) {
    index.push(
      `| ${issue.number} | ${kind(issue)} | [${issue.title}](${fileName(issue)}) | ${issue.state.toLowerCase()} |`,
    );
  }
}
writeFileSync(join(outDir, "README.md"), `${index.join("\n")}\n`);
console.log(`→ docs/issues/: ${issues.length} issues`);
